alter table api_keys enable row level security;
alter table key_models enable row level security;
alter table key_usage_hourly enable row level security;
alter table key_checks enable row level security;
alter table kaggle_accounts enable row level security;
alter table kaggle_sessions enable row level security;
alter table kaggle_session_events enable row level security;
alter table gpu_usage_weekly enable row level security;
alter table sessions enable row level security;
alter table general_keys enable row level security;
alter table general_key_logs enable row level security;
alter table plexus_endpoint enable row level security;